#!/usr/bin/env python3
"""Generate a drop-in replacement for one of SPP's sensor dylibs that forwards every exported
C function to the real library (renamed `<name>_real.dylib` alongside) and records each call:
the symbol name, integer register arguments, 64 bytes of stack arguments, and a 1008-byte
dump behind every argument that points at readable memory (so the parameter block is captured
whichever entry point carries it). `requestProcess` and `initialize` get full-signature wrappers
that also dump the input/output/CAMF buffers.

  python3 mkshim.py <real dylib (original or *_real.dylib)> <out shim.c>
  clang -O1 -target arm64-apple-ios14.0-macabi -isysroot $SDK -dynamiclib -o shim.dylib shim.c
"""
import subprocess, sys

real, out = sys.argv[1], sys.argv[2]
# Where the shim finds the real engine at run time. SPP loads *every* dylib it finds in
# MonoBundle/Sensor and registers it by its "libNN_" prefix, so a sibling named
# lib95_…_real.dylib was picked up as engine 95 too and took over requestProcess, bypassing
# the shim. Keep the real engine out of that directory: Sensor/real/<original name>.
nm = subprocess.run(["nm", "-gU", real], capture_output=True, text=True, check=True).stdout
funcs = []
for line in nm.splitlines():
    parts = line.split()
    if len(parts) != 3 or parts[1] != "T":
        continue
    sym = parts[2]
    if sym.startswith("__Z") or not sym.startswith("_"):
        continue   # C++ symbols are never dlsym'd by the host
    funcs.append(sym[1:])

special = {"initialize", "requestProcess"}
plain = [f for f in funcs if f not in special]
base = real.split("/")[-1]
realname = base if base.endswith("_real.dylib") else base.replace(".dylib", "_real.dylib")

c = []
c.append('/* generated by mkshim.py — forwards %d exports of %s with call logging */' % (len(funcs), base))
c.append('''#include <dlfcn.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <stdarg.h>
#include <unistd.h>
#include <sys/stat.h>
#include <malloc/malloc.h>
#include <mach/mach.h>
typedef struct { int32_t l, t, r, b; } stRECT;
typedef long (*fnRequestProcess)(void *, stRECT, uint32_t, const void *, void *, void *, void *, void *, uint16_t, void *);
typedef long (*fnInitialize)(const char *, void *, const char *);
static fnRequestProcess real_rp; static fnInitialize real_init; static int seq = 0;
static const char *capdir(void) { static char d[512]; if (!d[0]) { const char *e = getenv("SPPCAP_DIR"); snprintf(d, sizeof d, "%s", e ? e : "/tmp/sppcap"); mkdir(d, 0755); } return d; }
static void note(const char *fmt, ...) { char path[600]; snprintf(path, sizeof path, "%s/log.txt", capdir()); FILE *f = fopen(path, "a"); if (!f) return; va_list ap; va_start(ap, fmt); vfprintf(f, fmt, ap); va_end(ap); fputc('\\n', f); fclose(f); }
static void dump(const char *name, const void *p, size_t n) { if (!p || !n) return; char path[600]; snprintf(path, sizeof path, "%s/%03d_%s", capdir(), seq, name); FILE *f = fopen(path, "wb"); if (!f) return; fwrite(p, 1, n, f); fclose(f); }
static size_t cap(size_t n) { return n > (768u << 20) ? (768u << 20) : n; }
/* copy memory only if it is mapped: vm_read_overwrite fails instead of crashing */
static int safe_read(const void *src, void *dst, size_t n) {
  vm_size_t got = 0;
  kern_return_t kr = vm_read_overwrite(mach_task_self(), (vm_address_t)(uintptr_t)src, (vm_size_t)n, (vm_address_t)(uintptr_t)dst, &got);
  return kr == KERN_SUCCESS && got == n;
}
long initialize(const char *cert, void *capdata, const char *tmp) {
  char cwd[1024]; if (!getcwd(cwd, sizeof cwd)) strcpy(cwd, "?");
  note("initialize pid=%d cert='%s' tmp='%s' cwd='%s'", getpid(), cert ? cert : "(null)", tmp ? tmp : "(null)", cwd);
  long r = real_init(cert, capdata, tmp); note("initialize -> %ld", r); return r;
}
long requestProcess(void *P, stRECT loupe, uint32_t desig, const void *input, void *gs, void *rs, void *cb, void *obj, uint16_t outMB, void *out) {
  seq++; const uint8_t *p = P; dump("params.bin", P, 1008);
  unsigned req_w = p[28] | p[29] << 8, req_h = p[30] | p[31] << 8;
  void *camf = NULL, *lens = NULL, *uniq = NULL; memcpy(&camf, p + 48, 8); memcpy(&lens, p + 104, 8); memcpy(&uniq, p + 416, 8);
  size_t insz = input ? malloc_size(input) : 0, outsz = out ? malloc_size(out) : 0, camfsz = camf ? malloc_size(camf) : 0, lenssz = lens ? malloc_size(lens) : 0;
  char cwd[1024]; if (!getcwd(cwd, sizeof cwd)) strcpy(cwd, "?");
  note("requestProcess #%d desig=%u loupe=%d,%d,%d,%d outMB=%u obj=%p input=%p(%zu) output=%p(%zu) camf=%p(%zu) lens=%p(%zu) uniq='%s' cwd='%s' w=%u h=%u",
       seq, desig, loupe.l, loupe.t, loupe.r, loupe.b, outMB, obj, input, insz, out, outsz, camf, camfsz, lens, lenssz, uniq ? (const char *)uniq : "(null)", cwd, (unsigned)(p[28] | p[29] << 8), (unsigned)(p[30] | p[31] << 8));
  if (insz) dump("input.bin", input, cap(insz)); if (camfsz) dump("camf.bin", camf, cap(camfsz));
  if (lenssz) dump("lensprof.bin", lens, cap(lenssz)); else if (lens) dump("lensprof.txt", lens, strnlen((const char *)lens, 1 << 20));
  long r = real_rp(P, loupe, desig, input, gs, rs, cb, obj, outMB, out);
  note("requestProcess #%d -> %ld", seq, r);
  /* the engine keeps filling the display buffer from its worker thread after returning (progress
     callbacks reach 100% later), so give a large render time to finish before dumping it */
  if (out && r == 0) usleep(2500000);
  /* SPP's output buffer is a pinned managed array (malloc_size 0): size it from the BMP header the
     engine wrote (rows are padded to 4 bytes), falling back to the requested geometry. The engine
     may overwrite the request's w/h with the frame size, so use the values saved before the call. */
  if (!outsz && out && r == 0) {
    const uint8_t *o = out;
    uint32_t bmpsz = (uint32_t)o[2] | (uint32_t)o[3] << 8 | (uint32_t)o[4] << 16 | (uint32_t)o[5] << 24;
    if (o[0] == 'B' && o[1] == 'M' && bmpsz > 54 && bmpsz < (1u << 30)) outsz = bmpsz;
    else outsz = (size_t)req_w * req_h * (((desig & ~2u) == 5) ? 6 : 3) + 54;
  }
  if (outsz) dump("output.bin", out, cap(outsz)); dump("params_after.bin", P, 1008);
  return r;
}''')
c.append('void *shim_targets[%d];' % max(1, len(plain)))
c.append('static const char *plain_names[] = { %s };' % ", ".join('"%s"' % f for f in plain))
c.append('''/* called by every forwarding stub before the jump: regs = x0..x8, stk = the caller's stack arguments */
void shim_log_call(long idx, uint64_t *regs, uint64_t *stk) {
  static uint8_t buf[1008];
  seq++;
  note("call %s x0=%#llx x1=%#llx x2=%#llx x3=%#llx x4=%#llx x5=%#llx x6=%#llx x7=%#llx | stk %#llx %#llx %#llx %#llx %#llx %#llx %#llx %#llx",
       plain_names[idx], (unsigned long long)regs[0], (unsigned long long)regs[1], (unsigned long long)regs[2], (unsigned long long)regs[3],
       (unsigned long long)regs[4], (unsigned long long)regs[5], (unsigned long long)regs[6], (unsigned long long)regs[7],
       (unsigned long long)stk[0], (unsigned long long)stk[1], (unsigned long long)stk[2], (unsigned long long)stk[3],
       (unsigned long long)stk[4], (unsigned long long)stk[5], (unsigned long long)stk[6], (unsigned long long)stk[7]);
  for (int i = 0; i < 8; i++) {
    uint64_t v = regs[i];
    if (v < 0x10000 || v > 0x7fffffffffffULL) continue;
    if (!safe_read((const void *)(uintptr_t)v, buf, sizeof buf)) continue;
    char name[64]; snprintf(name, sizeof name, "%s_x%d.bin", plain_names[idx], i);
    dump(name, buf, sizeof buf);
    size_t ms = malloc_size((const void *)(uintptr_t)v);
    if (ms > sizeof buf) { snprintf(name, sizeof name, "%s_x%d_full.bin", plain_names[idx], i); dump(name, (const void *)(uintptr_t)v, cap(ms)); }
  }
}''')
for i, f in enumerate(plain):
    c.append('''__attribute__((naked)) void %s(void) { __asm__ volatile(
  "sub sp, sp, #240\\n\\t" "stp x29, x30, [sp, #224]\\n\\t"
  "stp x0, x1, [sp, #0]\\n\\t" "stp x2, x3, [sp, #16]\\n\\t" "stp x4, x5, [sp, #32]\\n\\t" "stp x6, x7, [sp, #48]\\n\\t" "str x8, [sp, #64]\\n\\t"
  "stp q0, q1, [sp, #80]\\n\\t" "stp q2, q3, [sp, #112]\\n\\t" "stp q4, q5, [sp, #144]\\n\\t" "stp q6, q7, [sp, #176]\\n\\t"
  "mov x0, #%d\\n\\t" "mov x1, sp\\n\\t" "add x2, sp, #240\\n\\t" "bl _shim_log_call\\n\\t"
  "ldp q0, q1, [sp, #80]\\n\\t" "ldp q2, q3, [sp, #112]\\n\\t" "ldp q4, q5, [sp, #144]\\n\\t" "ldp q6, q7, [sp, #176]\\n\\t"
  "ldp x0, x1, [sp, #0]\\n\\t" "ldp x2, x3, [sp, #16]\\n\\t" "ldp x4, x5, [sp, #32]\\n\\t" "ldp x6, x7, [sp, #48]\\n\\t" "ldr x8, [sp, #64]\\n\\t"
  "ldp x29, x30, [sp, #224]\\n\\t" "add sp, sp, #240\\n\\t"
  "adrp x16, _shim_targets@PAGE\\n\\t" "add x16, x16, _shim_targets@PAGEOFF\\n\\t" "ldr x16, [x16, #%d]\\n\\t" "br x16"); }''' % (f, i, i * 8))
c.append('''__attribute__((constructor)) static void shim_init(void) {
  Dl_info di; char path[2048] = "", dir[2048] = "", base[256] = "";
  if (dladdr((void *)shim_init, &di) && di.dli_fname) snprintf(path, sizeof path, "%s", di.dli_fname);
  char *slash = strrchr(path, '/');
  if (slash) { snprintf(base, sizeof base, "%s", slash + 1); *slash = 0; snprintf(dir, sizeof dir, "%s", path); }
  /* preferred: Sensor/real/<original name>, outside the directory SPP scans for engines */
  snprintf(path, sizeof path, "%s/real/%s", dir, base);
  if (access(path, R_OK) != 0) snprintf(path, sizeof path, "%s/%s", dir, "REAL_NAME");
  void *h = dlopen(path, RTLD_NOW | RTLD_LOCAL);
  note("shim loaded in pid %d; real engine %s -> %p%s%s", getpid(), path, h, h ? "" : " dlopen failed: ", h ? "" : dlerror());
  if (!h) return;
  real_init = (fnInitialize)dlsym(h, "initialize"); real_rp = (fnRequestProcess)dlsym(h, "requestProcess");
  for (int i = 0; i < (int)(sizeof plain_names / sizeof *plain_names); i++) shim_targets[i] = dlsym(h, plain_names[i]);
}''')
open(out, "w").write("\n".join(c).replace("REAL_NAME", realname) + "\n")
print("wrote", out, "forwarding+logging", len(plain), "functions +", sorted(special))
